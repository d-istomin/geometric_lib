def area(a, h):
    """Возвращает площадь треугольника по основанию и высоте.

    Параметры:
        a (float | int): основание (длина стороны) треугольника.
        h (float | int): высота треугольника, опущенная на основание a.

    Возвращаемое значение:
        float: площадь треугольника.

    Пример вызова:
        >>> area(6, 4)
        12.0
    """
    return a * h / 2


def perimeter(a, b, c):
    """Возвращает периметр треугольника по трём сторонам.

    Параметры:
        a (float | int): длина первой стороны треугольника.
        b (float | int): длина второй стороны треугольника.
        c (float | int): длина третьей стороны треугольника.

    Возвращаемое значение:
        float | int: периметр треугольника.

    Пример вызова:
        >>> perimeter(3, 4, 5)
        12
    """
    return a + b + c
